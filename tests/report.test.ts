const pull: PullInfo = {
  repoFullName: 'acme/vigil',
  provider: 'github',
  number: 7,
  title: 'Add login flow',
  author: 'alice',
  baseRef: 'main',
  headRef: 'feat/login',
  headSha: 'abc123',
  additions: 120,
  deletions: 30,
  changedFiles: 2,
};

function finding(
  severity: Severity,
  path: string,
  line: number,
  over: Partial<MergedFinding> = {},
): MergedFinding {
  return {
    ruleId: 'sample-rule',
    source: 'heuristic',
    category: 'quality',
    severity,
    confidence: 80,
    path,
    line,
    message: `Issue in ${path}`,
    suggestion: 'Fix it',
    ...over,
  };
}

function reportInput(over: Partial<ReportInput> = {}): ReportInput {
  return {
    pull,
    files: [],
    findings: [],
    similarFindings: [],
    learnings: [],
    heuristicsOnly: false,
    dryRun: false,
    testsMissing: false,
    reviewSeconds: 12,
    ...over,
  };
}

/** DiffFile fixture built from a real patch string; +/- counts derived from it. */
function file(
  path: string,
  patch: string,
  opts: { status?: string; previous?: string; additions?: number; deletions?: number } = {},
): DiffFile {
  const added = patch.split('\n').filter((l) => l.startsWith('+') && !l.startsWith('+++')).length;
  const removed = patch.split('\n').filter((l) => l.startsWith('-') && !l.startsWith('---')).length;
  return buildDiffFile({
    filename: path,
    previous_filename: opts.previous,
    status: opts.status ?? 'modified',
    additions: opts.additions ?? added,
    deletions: opts.deletions ?? removed,
    patch,
  });
}

// ---------------------------------------------------------------------------
// buildReviewReport
// ---------------------------------------------------------------------------

describe('buildReviewReport', () => {
  it('renders title, stat block, mode line and footer', () => {
    const report = buildReviewReport(reportInput());
    expect(report).toContain('## Vigil Review');
    expect(report).toContain('### Walkthrough');
    expect(report).toContain('**Add login flow** · 120 additions · 30 deletions · 2 files');
    expect(report).toContain('Mode: heuristics+LLM · Reviewed in 12s');
    expect(report).toContain(
      'Generated by **Vigil** — self-hosted SDLC agent · heuristics+LLM · PostgreSQL memory',
    );
    expect(report).not.toContain('dry-run');

    const heuristics = buildReviewReport(reportInput({ heuristicsOnly: true }));
    expect(heuristics).toContain('Mode: heuristics · Reviewed in 12s');
    expect(heuristics).toContain('heuristics · PostgreSQL memory');
  });

  it('renders the risk line and per-severity counts', () => {
    const findings = [
      finding('critical', 'src/a.ts', 1, { confidence: 100 }),
      finding('high', 'src/a.ts', 2, { confidence: 100 }),
      finding('medium', 'src/b.ts', 3, { confidence: 50 }),
      finding('medium', 'src/b.ts', 4, { confidence: 50 }),
      finding('low', 'src/c.ts', 5, { confidence: 40 }),
      finding('info', 'src/d.ts', 6, { confidence: 20 }),
    ];
    const score = riskScore(findings);
    expect(score).toBe(53); // sanity: matches the label asserted below

    const report = buildReviewReport(reportInput({ findings }));
    expect(report).toContain('**Risk score: 53/100 — High**');
    expect(report.split('\n')).toContain('1 critical · 1 high · 2 medium · 1 low · 1 info');
  });

  it('omits zero severities from the summary line', () => {
    const findings = [finding('critical', 'src/a.ts', 1), finding('low', 'src/b.ts', 2)];
    const report = buildReviewReport(reportInput({ findings }));
    expect(report.split('\n')).toContain('1 critical · 1 low');
    expect(report).not.toContain('0 high');
    expect(report).not.toContain('high ·');
  });

  it('orders critical findings before low ones and renders finding details', () => {
    const findings = [
      finding('low', 'src/low.ts', 9, { confidence: 60 }),
      finding('critical', 'src/crit.ts', 3, { confidence: 90, source: 'llm', ruleId: null }),
    ];
    const report = buildReviewReport(reportInput({ findings }));

    const findingsIdx = report.indexOf('### Findings');
    const critIdx = report.indexOf('#### CRITICAL');
    const lowIdx = report.indexOf('#### LOW');
    expect(findingsIdx).toBeGreaterThan(-1);
    expect(critIdx).toBeGreaterThan(findingsIdx);
    expect(lowIdx).toBeGreaterThan(critIdx);

    expect(report).toContain('- **src/crit.ts:3** — Issue in src/crit.ts');
    expect(report).toContain('  - Suggestion: Fix it');
    expect(report).toContain('  - Confidence: 90% · source: llm');
    expect(report).toContain('  - Confidence: 60% · source: heuristic');
  });

  it('renders a clean-diff line when there are no findings', () => {
    const report = buildReviewReport(reportInput());
    expect(report).toContain('**No findings. Clean diff.**');
    expect(report).toContain('**Risk score: 0/100 — Low**');
    expect(report).not.toContain('### Findings');
    expect(report).not.toContain('#### ');
  });

  it('embeds a mermaid file graph when there are 2+ files', () => {
    const files = [
      file('src/a.ts', '@@ -1,2 +1,3 @@\n ctx\n+function foo() {}\n+const x = 1;'),
      file('tests/a.test.ts', '@@ -1 +1,2 @@\n ctx\n+test("x", () => {});'),
    ];
    const report = buildReviewReport(reportInput({ files }));

    expect(report).toContain('### File graph');
    expect(report).toContain('```mermaid');
    expect(report).toContain('graph LR');
    expect(report).toContain('subgraph dir_src["src"]');
    expect(report).toContain('f_src_a_ts["src/a.ts"]');
    expect(report).toContain('repo --> f_src_a_ts');
    expect(report).toContain('classDef file');
    expect(report.match(/```mermaid[\s\S]*?```/)).not.toBeNull(); // fence closes
  });

  it('omits the file graph for single-file diffs and beyond 25 files', () => {
    const single = buildReviewReport(
      reportInput({ files: [file('src/a.ts', '@@ -1 +1,2 @@\n+function foo() {}')] }),
    );
    expect(single).not.toContain('```mermaid');
    expect(single).not.toContain('### File graph');

    const many = Array.from({ length: 26 }, (_, i) =>
      file(`src/m${i}.ts`, '@@ -1 +1,2 @@\n+const x = 1;', { status: 'added' }),
    );
    const report = buildReviewReport(reportInput({ files: many }));
    expect(report).not.toContain('```mermaid');
  });

  it('mentions dry-run in the footer only when requested', () => {
    const report = buildReviewReport(reportInput({ dryRun: true }));
    expect(report).toContain(
      'Generated by **Vigil** — self-hosted SDLC agent · heuristics+LLM · PostgreSQL memory · dry-run (not posted)',
    );
  });

  it('renders test impact, similar past findings and learnings (capped at 5)', () => {
    const files = [file('src/a.ts', '@@ -1 +1,2 @@\n+function foo() {}')];
    const similarFindings = Array.from({ length: 7 }, (_, i) => ({
      path: `src/s${i}.ts`,
      ruleId: 'sample-rule',
      message: `past issue ${i}`,
      when: '2025-01-05T10:00:00Z',
      prNumber: 100 + i,
    }));
    const learnings = [
      'Always check X',
      'Prefer Y',
      'Z is banned',
      'W required',
      'V style',
      'U rule (should be cut)',
    ];

    const report = buildReviewReport(
      reportInput({ files, testsMissing: true, similarFindings, learnings }),
    );

    expect(report).toContain('### Test impact');
    expect(report).toContain('1 source file changed with no test changes');
    expect(report).toContain('### Similar past findings');
    expect(report).toContain('- src/s0.ts — past issue 0 (PR #100, date 2025-01-05)');
    expect(report).toContain('(PR #104, date 2025-01-05)'); // 5th of 7
    expect(report).not.toContain('src/s5.ts');
    expect(report).not.toContain('PR #106');
    expect(report).toContain('### Applied team knowledge');
    expect(report.split('\n')).toContain('- V style');
    expect(report).not.toContain('U rule (should be cut)');
  });

  it('embeds llm walkthrough paragraphs as indented quotes', () => {
    const files = [file('src/auth.ts', '@@ -1 +1,2 @@\n ctx\n+function login() {}')];
    const report = buildReviewReport(
      reportInput({ files, llmWalkthrough: { 'src/auth.ts': 'Reworks the login flow.' } }),
    );
    expect(report).toContain('  > Reworks the login flow.');
  });

  it('caps the walkthrough at 30 files', () => {
    const files = Array.from({ length: 32 }, (_, i) =>
      file(`src/f${i}.ts`, '@@ -1 +1,2 @@\n+const x = 1;', { status: 'added' }),
    );
    const report = buildReviewReport(reportInput({ files }));
    expect(report).toContain('- **src/f29.ts** (added, +1/-0)');
    expect(report).toContain('- +2 more files');
    expect(report).not.toContain('src/f30.ts');
  });
});

