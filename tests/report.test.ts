describe('buildStandupReport', () => {
  it('includes merges and omits empty sections entirely', () => {
    const data: StandupData = {
      since: '2025-01-08T09:00:00Z',
      merges: [{ repo: 'acme/api', number: 42, title: 'Fix pagination', author: 'bob' }],
      stale: [],
      alerts: [],
      deploys: [],
    };
    const report = buildStandupReport(data);
    expect(report).toContain('## Standup — 2025-01-08');
    expect(report).toContain('### Merged since 2025-01-08');
    expect(report).toContain('- acme/api#42 Fix pagination · bob');
    expect(report).not.toContain('### Stale PRs');
    expect(report).not.toContain('### Alerts');
    expect(report).not.toContain('### Deploys');
  });

  it('renders stale PRs, alerts and deploys when present', () => {
    const data: StandupData = {
      since: '2025-01-08',
      merges: [],
      stale: [{ repo: 'acme/web', number: 7, title: 'Refactor nav', idleHours: 36 }],
      alerts: [{ source: 'grafana', title: 'CPU saturation', when: '2025-01-09T10:00:00Z' }],
      deploys: [{ repo: 'acme/api', ref: 'main', at: '2025-01-09T08:00:00Z' }],
    };
    const report = buildStandupReport(data);
    expect(report).toContain('### Stale PRs');
    expect(report).toContain('- acme/web#7 idle 36h — Refactor nav');
    expect(report).toContain('### Alerts');
    expect(report).toContain('- [grafana] CPU saturation — 2025-01-09T10:00:00Z');
    expect(report).toContain('### Deploys');
    expect(report).toContain('- acme/api main at 2025-01-09T08:00:00Z');
    expect(report).not.toContain('### Merged since');
  });

  it('outputs a single nothing-to-report line when all sections are empty', () => {
    const report = buildStandupReport({
      since: '2025-01-08',
      merges: [],
      stale: [],
      alerts: [],
      deploys: [],
    });
    expect(report).toContain('(nothing to report)');
    expect(report).not.toContain('###');
  });
});

