    const report = buildPostmortem(input);

    expect(report).toContain('# Postmortem: API outage');
    expect(report).toContain('**Severity:** SEV-1');
    expect(report).toContain('## Summary');
    expect(report).toContain('## Impact');
    expect(report).toContain('5% of requests failed for 12 minutes.');
    expect(report).toContain('## Timeline');
    expect(report).toContain('| Time | Event |');
    expect(report).toContain('| --- | --- |');
