describe('buildWalkthrough', () => {
  it('describes added functions and imports from the patch, no LLM needed', () => {
    const f = file(
      'src/foo.ts',
      ['@@ -1,3 +1,6 @@', ' keep', '+function foo() {}', '+function bar() {}', '+import x from "y";', '+const z = 1;'].join('\n'),
    );
    const walkthrough = buildWalkthrough([f]);
    expect(walkthrough).toContain('- **src/foo.ts** (modified, +4/-0)');
    expect(walkthrough).toMatch(/Adds 2 functions and 1 import\./);
  });

  it('counts exported symbols when no functions or imports are added', () => {
    const f = file('src/api.ts', '@@ -1 +1,3 @@\n+export const A = 1;\n+export interface B {}');
    expect(buildWalkthrough([f])).toContain('Adds 2 exported symbols.');
  });

  it('appends the llm walkthrough paragraph as an indented quote', () => {
    const f = file('src/foo.ts', '@@ -1 +1,2 @@\n ctx\n+function foo() {}');
    const walkthrough = buildWalkthrough([f], { 'src/foo.ts': 'This module introduces the foo helper.' });
    expect(walkthrough).toContain('  > This module introduces the foo helper.');
  });

  it('describes renames, cleanups and binary files', () => {
    const renamed = file('src/new.ts', '@@ -1 +1,2 @@\n ctx\n+const a = 1;', {
      status: 'renamed',
      previous: 'src/old.ts',
    });
    expect(buildWalkthrough([renamed])).toContain('Renames from src/old.ts.');

    const cleanup = file('src/gone.ts', '@@ -1,3 +0,0 @@\n-a\n-b\n-c', { status: 'removed' });
    expect(buildWalkthrough([cleanup])).toContain('Removes 3 lines (cleanup).');

    const binary = buildDiffFile({
      filename: 'assets/logo.png',
      status: 'modified',
      additions: 0,
      deletions: 0,
      patch: null,
    });
    expect(buildWalkthrough([binary])).toContain('Binary or no textual hunks.');
  });
});

